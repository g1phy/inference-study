import { useMemo } from 'react'
import { Callout, Chapter, ChapterLink, CodeBlock, Deeper, SimulatorLink, Takeaways, Term, fmt } from '@/ui'
import { useSettings } from '@/state/settings'
import { getInterconnect } from '@/engine/data/interconnects'
import { kvBytesForSeq, kvBytesPerToken, prefillMs, transferMs } from '@/engine/perf'
import { simConfig } from '../batching/config'
import { SpecTable } from '../batching/chart'
import { CompareFigure } from './CompareFigure'
import { CondFigure } from './CondFigure'
import { DynamoFlowFigure } from './DynamoFlowFigure'
import { LanesFigure } from './LanesFigure'
import { TransferFigure } from './TransferFigure'
import { nvlinkFor } from './logic'

const PROMPT = 8192

export default function DisaggregationChapter() {
  const [settings] = useSettings()
  const cfg = simConfig(settings.modelId, settings.gpuId)
  const n = useMemo(() => {
    const perToken = kvBytesPerToken(cfg.model)
    const kv = kvBytesForSeq(cfg.model, PROMPT)
    const prefill = prefillMs(cfg.model, cfg.gpu, PROMPT, { gpus: cfg.tp, dtype: cfg.dtype })
    const ib = transferMs(kv, getInterconnect('ib-ndr').GBs)
    const nv = transferMs(kv, nvlinkFor(cfg.gpu).GBs)
    const tcp = transferMs(kv, getInterconnect('tcp-25g').GBs)
    return { perToken, kv, prefill, ib, nv, tcp }
  }, [cfg])

  return (
    <Chapter
      id="disaggregation"
      lead={
        <>
          В агрегированном режиме одни и те же GPU делают и prefill, и decode, и фазы мешают друг другу. Дезагрегация разводит их по разным
          пулам: prefill-воркеры считают KV cache промпта и передают его decode-воркерам по быстрому каналу между GPU.
        </>
      }
    >
      <h3>Две фазы с разными аппетитами</h3>
      <p>
        Из главы <ChapterLink to="prefill-decode" /> мы знаем, что запрос проходит две фазы. <Term t="Prefill" /> считает весь промпт за один проход:
        работы много, она упирается в вычисления и определяет <Term t="TTFT" />. <Term t="Decode" /> выдаёт по токену за шаг: вычислений мало, шаг
        упирается в чтение памяти и определяет <Term t="ITL" />.
      </p>
      <p>
        В <Term t="Aggregated serving">агрегированном режиме</Term> (agg) каждый GPU делает обе фазы. Continuous batching и chunked prefill из{' '}
        <ChapterLink to="batching">прошлой главы</ChapterLink> смешивают их аккуратно, но не разделяют: каждый шаг с куском prefill длиннее чистого шага
        decode, и все, кто в этот момент генерирует, ждут. Кроме того, обе фазы вынуждены жить с одним и тем же железом, параллелизмом и настройками
        движка.
      </p>
      <p>
        <Term t="Disaggregated serving">Дезагрегированный режим</Term> (disagg, его ещё называют non-agg или PD-дезагрегацией) разделяет работу.{' '}
        <Term t="Prefill worker / decode worker">Prefill-воркеры</Term> только считают промпты, decode-воркеры только генерируют. Между ними едет
        KV cache промпта: это <Term t="KV transfer">передача KV</Term>.
      </p>
      <p>
        Как это выглядит на одном и том же потоке запросов? Ниже 12 запросов с короткими и длинными промптами в обоих режимах; в каждом режиме{' '}
        {cfg.tp > 1 ? `два воркера по ${cfg.tp} GPU` : 'два GPU'}.
      </p>
      <LanesFigure />
      <p>
        В агрегированном режиме синие блоки длинных промптов врезаются в оранжевую ленту decode, и на дорожке ITL видны плато: все запросы,
        которые генерировали на этом {cfg.tp > 1 ? 'воркере' : 'GPU'}, стояли и ждали. В дезагрегированном режиме{' '}
        {cfg.tp > 1 ? 'decode-воркер' : 'decode-GPU'} занят только короткими одинаковыми шагами, ITL ровный. Цена тоже видна: prefill теперь делает{' '}
        {cfg.tp > 1 ? 'один воркер вместо двух' : 'один GPU вместо двух'}, промпты стоят в очереди, и TTFT растёт; к нему добавляется передача KV:
        небольшая по RDMA, почти незаметная по NVLink и огромная по TCP.
      </p>
      <SimulatorLink stage="transfer" />

      <h3>Где выигрыш, а где нет</h3>
      <p>
        Двенадцать запросов показывают механику, но не отвечают на вопрос, какой режим лучше. Для этого нужен поток под нагрузкой и метрики с
        хвостами. Ниже один и тот же поток со случайными моментами прихода (пуассоновский) обслуживают четыре воркера: в агрегированном режиме все
        четыре делают всё, в дезагрегированном их делят на prefill и decode. Такое разбиение записывают как <Term t="xPyD" />: 3P1D значит три
        prefill-воркера и один decode.
      </p>
      <CompareFigure />
      <p>Из этой симуляции стоит вынести пять вещей.</p>
      <ul>
        <li>
          Дезагрегация выравнивает ITL: хвост p99 почти равен медиане, потому что чужие промпты больше не врезаются в шаги decode. Медиана при этом
          может вырасти: в 3P1D весь decode идёт на одном воркере, и его batch вчетверо больше.
        </li>
        <li>
          Throughput на GPU она сама по себе не повышает: документация vLLM прямо пишет, что смысл дезагрегации в предсказуемом ITL. Растёт{' '}
          <Term t="Goodput">goodput</Term>: сколько запросов в секунду система обслуживает в рамках SLO на тех же GPU. Именно его DistServe увеличил
          до 7,4 раза.
        </li>
        <li>TTFT теперь определяет размер prefill-пула: если prefill-воркеров мало, очередь растёт, и TTFT уходит в секунды.</li>
        <li>
          Правильное соотношение зависит от формы трафика: длинные промпты требуют больше prefill-воркеров, длинные ответы больше decode. Поэтому
          xPyD подбирают под нагрузку и меняют на лету.
        </li>
        <li>
          Короткие промпты на небольшой модели дезагрегация не ускоряет: в профиле «Чат» на Qwen3-8B (H100) все схемы держат SLO, а TTFT у
          агрегированного режима ниже.
        </li>
      </ul>
      <Callout kind="intuition">
        Агрегированный режим похож на кухню, где каждый повар и режет продукты для новых заказов, и доводит до готовности уже начатые: стоит ему
        взяться за большую нарезку, все его сковородки ждут. Дезагрегация делит кухню на заготовочный цех и раздачу. Нарезка больше не мешает
        раздаче, но заготовки теперь нужно доставить из цеха.
      </Callout>

      <h3>Цена передачи KV</h3>
      <p>
        KV cache промпта весит много. У {cfg.model.name} это {fmt.bytes(n.perToken, { mode: 'binary' })} на токен, значит промпт на{' '}
        {fmt.tokens(PROMPT)} занимает {fmt.bytes(n.kv)}. Пока KV не доехал, decode не может начать, поэтому время передачи прямо прибавляется к TTFT.
        Сравните его со временем самого prefill.
      </p>
      <TransferFigure />
      <p>
        Для {cfg.model.name} и промпта в {fmt.tokens(PROMPT)}: prefill около {fmt.ms(n.prefill)}, передача по NVLink {fmt.ms(n.nv)} (
        {fmt.pct(n.nv / n.prefill)} от prefill), по одной карте InfiniBand {fmt.ms(n.ib)} ({fmt.pct(n.ib / n.prefill)}), по TCP без RDMA{' '}
        {fmt.ms(n.tcp)}. По <Term t="NVLink / NVSwitch">NVLink</Term> передача почти не видна в TTFT. По <Term t="RDMA / GPUDirect RDMA">RDMA</Term>{' '}
        (<Term t="InfiniBand" /> или RoCE) всё решает число сетевых карт: при tensor parallel каждый GPU шлёт свою долю KV по своей карте, и время
        делится на число GPU, а через одну карту на быстром GPU это уже заметная прибавка к TTFT. По обычному TCP передача сравнима с prefill или
        дольше, и смысл дезагрегации пропадает.
      </p>
      <Callout kind="production" title="сеть решает">
        <p>
          Передачей занимается <Term t="NIXL" />, библиотека NVIDIA для передачи данных точка-точка: она копирует блоки KV из видеопамяти одного GPU в
          видеопамять другого через RDMA или NVLink, почти без участия CPU, и не блокирует GPU, пока тот считает другие запросы. Документация Dynamo
          предупреждает, что без RDMA передача откатывается на TCP и всё замедляется в сотни раз. В их примере TTFT около 98 с, а с RDMA от 200 до
          500 мс.
        </p>
        <p>
          Подвох Kubernetes: по умолчанию изоляция процессов и раздача GPU по подам закрывают NVLink между подами, поэтому даже prefill- и
          decode-воркеры на одной ноде передают KV через сетевую карту. NVLink доступен, только если поды делят пространство процессов хоста (hostPID)
          и видят GPU друг друга, а это ослабляет изоляцию (документация Dynamo). Поэтому цену передачи в проде считайте по RDMA.
        </p>
        <p>
          KV в FP8 вдвое уменьшает объём передачи и вдвое увеличивает число запросов, которые помещаются в память decode-воркеров; поэтому квантизация KV и дезагрегация хорошо работают
          вместе (<ChapterLink to="quantization" />
          ).
        </p>
      </Callout>

      <h3>Как это устроено в Dynamo</h3>
      <p>
        В <Term t="NVIDIA Dynamo">Dynamo</Term> дирижёр сидит во frontend. Компонент{' '}
        <Term t="PrefillRouter">
          <code>PrefillRouter</code>
        </Term>{' '}
        сначала выбирает prefill-воркер и
        отправляет ему копию запроса с <code>max_tokens = 1</code>, получает в ответ «квитанцию» о том, где лежит готовый KV, и только потом
        выбирает decode-воркер и отдаёт ему запрос вместе с квитанцией. Сам KV decode-воркер забирает напрямую с GPU prefill-воркера через NIXL.
      </p>
      <DynamoFlowFigure />
      <p>
        У vLLM с NixlConnector (так в Dynamo) передача устроена как pull: decode-воркер читает блоки из памяти prefill-воркера, а тот держит их, пока
        их не заберут. У SGLang наоборот, push: decode заранее выделяет страницы, а prefill сам пишет туда KV. Адрес встречи (bootstrap) известен
        заранее, поэтому роутер отправляет оба запроса почти одновременно, не дожидаясь конца prefill. Подробнее про остальные компоненты Dynamo в
        главе <ChapterLink to="dynamo" />.
      </p>
      <Callout kind="pitfall" title="кто получает запрос первым">
        В книге «Inference Engineering» и в старой документации Dynamo запрос сначала приходил на decode-воркер, и тот решал, отдавать ли prefill
        на сторону. В текущем Dynamo порядок обратный: frontend сам выбирает prefill-воркер первым, а decode-воркер получает запрос уже с
        метаданными для передачи KV. Старая схема описана ниже в «Глубже».
      </Callout>

      <h3>Conditional disaggregation: иногда prefill выгоднее сделать на месте</h3>
      <p>
        Гонять KV по сети выгодно не всегда. Если у decode-воркера, на который пойдёт запрос, уже лежит почти весь длинный диалог (prefix cache, глава{' '}
        <ChapterLink to="prefix-caching" />
        ), проще досчитать остаток на месте. Для этого в Dynamo есть <Term t="Conditional disaggregation">conditional disaggregation</Term>: экспериментальный режим роутера, флаг{' '}
        <code>--router-conditional-disagg</code> вместе с <code>--router-mode kv</code>. Роутеру нужны <Term t="KV events" /> от decode-воркеров,
        чтобы знать их кэш (как роутер узнаёт, что лежит в кэше, глава <ChapterLink to="routing" />); поддерживаются vLLM и TensorRT-LLM, SGLang пока
        нет.
      </p>
      <CondFigure />
      <p>
        Главный неочевидный момент: по умолчанию решает не длина промпта, а доля закэшированного. Короткий промпт без кэша всё равно уходит на
        prefill-воркер. Локальный prefill включается, когда досчитать нужно мало и в абсолютных токенах, и относительно всего промпта, то есть в
        длинных многоходовых диалогах и у агентов.
      </p>

      <Deeper title="когда дезагрегация окупается, а когда нет">
        <p>Книга называет три условия, и нужны все три сразу:</p>
        <ul>
          <li>большой трафик, от 100 млн до 1 млрд токенов в сутки (порог зависит от размера модели);</li>
          <li>большая модель, от 100 млрд параметров;</li>
          <li>prefill-тяжёлая нагрузка: длинные входы и короткие ответы. Классический пример: большая модель в редакторе кода, куда шлют большие куски проекта.</li>
        </ul>
        <p>
          Без первых двух условий деньги уходят на лишние GPU. Без третьего выгоднее просто добавить агрегированных реплик. Документация Dynamo
          добавляет: при низкой конкурентности агрегированный воркер часто лучше (нет передачи и дробления памяти на пулы), а если узкое место в
          ёмкости KV на decode, лишние prefill-реплики общую ёмкость даже уменьшают.
        </p>
        <p>
          Отдельный довод: жёсткий SLO по ITL. Если продукт не прощает подвисаний (голосовые ассистенты, агенты, стриминг кода), дезагрегация
          убирает их почти полностью, тогда как в агрегированном режиме их можно только уменьшить бюджетом шага.
        </p>
        <p>
          Ещё один довод за дезагрегацию: фазам можно дать разный параллелизм (<ChapterLink to="parallelism" />
          ). Prefill упирается в вычисления и обычно обходится меньшим TP; decode упирается в память и выигрывает от большого KV-пула. DeepSeek в проде
          держит prefill на EP32 (4 ноды), а decode на EP144 (18 нод). DistServe, статья, где эту идею развили, сообщает до 7,4× больше запросов в рамках
          SLO или в 12,6 раза более жёсткий SLO.
        </p>
        <p>
          Новые узкие места дезагрегации: очередь prefill (её держат порогами и перестройкой xPyD) и нехватка KV на decode-воркерах (её лечат FP8 KV
          и выгрузкой KV на уровни ниже, глава <ChapterLink to="kv-tiers" />
          ).
        </p>
      </Deeper>

      <Deeper title="xPyD: как подобрать соотношение пулов">
        <p>
          Грубый расчёт на условных числах. Пусть приходит 20 запросов в секунду, после prefix cache в промпте {fmt.int(6000)} токенов, ответ 400
          токенов. Один prefill-воркер считает {fmt.int(40000)} ток/с промпта, decode-воркер держит 64 потока по 50 ток/с.
        </p>
        <SpecTable
          caption="Подбор xPyD на условных числах"
          minWidth={460}
          head={['Шаг', 'Расчёт', 'Итог']}
          rows={[
            ['Спрос на prefill', `20 × ${fmt.int(6000)} = ${fmt.int(120000)} ток/с`, '3 P'],
            ['Спрос на decode', 'запрос живёт 400 / 50 = 8 с, одновременно 20 × 8 = 160 потоков, по 64 на воркер', '3 D'],
            ['Больше попаданий в кэш', `промпт после кэша ${fmt.int(2000)} токенов, ${fmt.int(40000)} ток/с хватает одному`, '1P3D'],
            ['Ответы стали длиннее', `reasoning, ${fmt.int(1200)} токенов; промпт снова ${fmt.int(6000)}: 480 потоков`, '3P8D'],
          ]}
        />
        <p>
          Соотношение оказывается функцией формы трафика. Поэтому в Dynamo число prefill- и decode-воркеров меняется на лету: новый воркер
          регистрируется и сообщает свою KV-ёмкость, уходящий дорабатывает запросы и снимается с регистрации. Planner Dynamo масштабирует пулы
          отдельно, под цели по TTFT и ITL.
        </p>
      </Deeper>

      <Deeper title="старый дизайн Dynamo: сначала decode и очередь prefill в NATS">
        <p>
          В документации Dynamo версий 0.x (до 1.0) и в книге запрос сначала попадал на decode-воркер. Тот решал, делать prefill у себя или удалённо: удалённо,
          если длина промпта без учёта попаданий в кэш больше порога и очередь prefill короче заданной. Для удалённого prefill decode-воркер
          выделял блоки KV и клал задачу в глобальную очередь prefill на NATS JetStream.
        </p>
        <p>
          Prefill-воркер забирал задачу, читал через NIXL уже закэшированные блоки с decode-воркера, считал остальное и записывал готовые блоки прямо
          в выделенную память decode-воркера. Метаданные NIXL всех блоков лежали в etcd, поэтому в запросе передавались только номера блоков. Если
          TP у prefill и decode разный, специальное ядро транспонировало блоки под нужную раскладку.
        </p>
        <p>
          Сейчас решение принимает <code>PrefillRouter</code> во frontend (код появился в v0.7.0, документация перешла на него в v1.0.0), а etcd и
          NATS для запуска больше не обязательны. Если prefill-воркеров нет совсем, запрос идёт прямо на backend; флаг <code>--decode-fallback</code>{' '}
          разрешает тогда агрегированный режим.
        </p>
      </Deeper>

      <Deeper title="кто сэмплирует первый токен">
        <p>
          По книге первый токен считает prefill-движок. В реальных движках по-разному. В пути Dynamo с vLLM токен prefill-воркера отбрасывается, а
          decode-воркер сам пересчитывает последнюю позицию промпта и сэмплирует первый выходной токен. В SGLang prefill сэмплирует первый токен (с
          маской structured output, если она есть), а decode его воспроизводит. TensorRT-LLM передаёт первый токен внутри непрозрачных метаданных.
        </p>
        <p>
          Это важно для structured output (<ChapterLink to="structured-output" />
          ): маска грамматики применяется в сэмплере, и в vLLM вся грамматика работает на decode-стороне.
        </p>
        <CodeBlock
          lang="bash"
          title="роли воркеров в Dynamo с vLLM"
          code={
            'python -m dynamo.vllm --model Qwen/Qwen3-8B --disaggregation-mode prefill \\\n  --kv-transfer-config \'{"kv_connector":"NixlConnector","kv_role":"kv_producer"}\'\n\npython -m dynamo.vllm --model Qwen/Qwen3-8B --disaggregation-mode decode \\\n  --kv-transfer-config \'{"kv_connector":"NixlConnector","kv_role":"kv_consumer"}\''
          }
        />
      </Deeper>

      <Takeaways
        items={[
          <>В агрегированном режиме prefill отнимает шаги у decode, и у всех генерирующих на этом GPU прыгает ITL. Дезагрегация разводит фазы по пулам, и шаги decode остаются короткими и ровными.</>,
          <>Дезагрегация не бесплатна: KV нужно перевезти (нужен NVLink или RDMA, по TCP выигрыш пропадает), TTFT зависит от размера prefill-пула, а throughput на GPU сам не растёт.</>,
          <>
            В Dynamo <code>PrefillRouter</code> во frontend сначала выбирает prefill-воркер (клон запроса с <code>max_tokens = 1</code>), потом
            decode-воркер получает <code>disaggregated_params</code> и забирает KV через NIXL.
          </>,
          <>Окупается на масштабе: длинные промпты, жёсткий SLO по ITL, большие модели, разный параллелизм фаз. Соотношение xPyD подбирают под форму трафика.</>,
        ]}
      />
    </Chapter>
  )
}
