import { Callout, Chapter, ChapterLink, Deeper, Formula, SimulatorLink, Takeaways, Term, fmt } from '@/ui'
import { getModel } from '@/engine/data/models'
import { weightBytes } from '@/engine/perf'
import { QWEN3_LOGITS_WIDTH } from '@/engine/tokenizer'
import { PromptTableFigure } from './PromptTableFigure'
import { MeaningMapFigure } from './MeaningMapFigure'
import { RopeFigure } from './RopeFigure'

/** Размер токенизатора Qwen3 (обычные + added tokens), SPEC §8.7; ширина логитов берётся из движка. */
const QWEN3_TOKENIZER_SIZE = 151_669
const QWEN3_BPE_SIZE = 151_643

export default function EmbeddingsChapter() {
  const m = getModel('qwen3-8b')
  const tableParams = m.vocab * m.hidden
  const tableBytes = tableParams * 2
  const emptyRows = QWEN3_LOGITS_WIDTH - QWEN3_TOKENIZER_SIZE
  const llama = getModel('llama-3.1-8b')
  const big = getModel('qwen3-235b-a22b')

  return (
    <Chapter
      id="embeddings"
      lead={
        <>
          Номер токена сам по себе ничего не значит. Каждый ID выбирает строку в большой таблице эмбеддингов: вектор из d_model чисел
          (у {m.name} их {fmt.int(m.hidden)}). С этого момента модель работает только с векторами.
        </>
      }
    >
      <p>
        После <ChapterLink to="tokenization">токенизации</ChapterLink> запрос превратился в список целых чисел. Например, токен «·KV» (точка
        обозначает пробел перед словом) в <Term t="словарь">словаре</Term> Qwen3 имеет номер {fmt.int(84648)}, а «·cache» номер{' '}
        {fmt.int(6500)}. С такими числами нельзя делать арифметику: {fmt.int(84648)} не «больше» {fmt.int(6500)} ни в каком полезном смысле,
        это просто номера строк в справочнике.
      </p>
      <p>
        Поэтому первым делом каждому ID сопоставляют вектор: набор чисел, выученный при обучении. Все векторы лежат в одной таблице, по строке
        на каждый токен словаря, и номер строки равен ID. Вектор из этой таблицы называют <Term t="эмбеддинг">эмбеддингом</Term> (embedding), а
        саму таблицу embedding table.
      </p>
      <p>
        Операция предельно простая: никаких умножений, только «взять строку номер ID». Для промпта из N токенов получается матрица N × d_model.
        Число d_model (в <Term t="config.json" /> оно называется <code>hidden_size</code>) называют шириной модели: вектор такой длины есть у
        каждого токена на входе, между слоями и после последнего слоя. Внутри слоя он бывает и шире (MLP {m.name} временно расширяет его до{' '}
        {fmt.int(m.intermediate)}), об этом в следующей главе.
      </p>
      <p>Вот что происходит с вашим запросом из симулятора. Какие строки таблицы он выбирает и что получается на выходе?</p>

      <PromptTableFigure />

      <p>На что обратить внимание.</p>
      <ul>
        <li>
          ID разбросаны по всей таблице, и строки читаются вразнобой. Для GPU это обычное чтение памяти, оно дешёвое по сравнению с умножениями
          матриц в слоях.
        </li>
        <li>Одинаковые токены дают одинаковые векторы, где бы они ни стояли: позиция токена в промпте при выборе строки не участвует.</li>
        <li>
          Таблица большая. У {m.name} это {fmt.int(m.vocab)} строк по {fmt.int(m.hidden)} чисел: около {fmt.compact(tableParams)} параметров и{' '}
          {fmt.bytes(tableBytes)} в BF16. А матрица промпта весит всего {fmt.bytes(m.hidden * 2)} на токен, на порядки меньше таблицы (точное
          число для вашего запроса в фигуре выше).
        </li>
      </ul>

      <Callout kind="precise" title={`почему строк ${fmt.int(QWEN3_LOGITS_WIDTH)}, а не ${fmt.int(QWEN3_TOKENIZER_SIZE)}`}>
        <p>
          В токенизаторе Qwen3 {fmt.int(QWEN3_TOKENIZER_SIZE)} токенов: {fmt.int(QWEN3_BPE_SIZE)} обычных и{' '}
          {QWEN3_TOKENIZER_SIZE - QWEN3_BPE_SIZE} служебных. В таблице {fmt.int(QWEN3_LOGITS_WIDTH)} строк, и последние {emptyRows} не выбирает
          ни один токен: размер добит до числа, удобного для GPU ({fmt.int(QWEN3_LOGITS_WIDTH)} делится на 128).
        </p>
        <p>
          Такой же ширины вектор логитов на выходе модели. Поэтому маски structured output и другие операции над логитами считаются по{' '}
          {fmt.int(QWEN3_LOGITS_WIDTH)} позициям, а не по размеру токенизатора (<ChapterLink to="structured-output" />
          ).
        </p>
        <p>
          На выходе у {m.name} есть вторая матрица того же размера, <Term t="LM head" />: ещё {fmt.bytes(tableBytes)}. У маленьких Qwen3 (0.6B,
          1.7B, 4B) таблица и LM head общие: в config.json у них стоит <code>tie_word_embeddings: true</code>.
        </p>
      </Callout>

      <Callout kind="production" title="где это в инференсе">
        <p>
          От клиента до GPU едут не векторы, а ID: токенизация идёт на CPU, а воркер получает целые числа. Lookup выполняется на GPU в начале
          каждого <Term t="forward pass" /> (прохода модели по всем слоям): в <Term t="prefill" /> сразу для всех токенов промпта, в{' '}
          <Term t="decode" /> для одного нового токена на шаге.
        </p>
        <p>
          Таблица лежит в <Term t="память GPU">памяти GPU</Term> вместе с остальными <Term t="веса">весами</Term>: {fmt.bytes(tableBytes)} из{' '}
          {fmt.bytes(weightBytes(m, 'bf16'))} у {m.name} в BF16. У {llama.name} таблица {fmt.int(llama.vocab)} × {fmt.int(llama.hidden)}, это{' '}
          {fmt.pct((llama.vocab * llama.hidden) / (llama.paramsB * 1e9))} модели. У {big.name} таблица той же ширины, что у {m.name}, но
          занимает всего {fmt.pct((big.vocab * big.hidden) / (big.paramsB * 1e9))} параметров.
        </p>
      </Callout>
      <SimulatorLink stage="prefill" />

      <h3>Что значат числа в векторе</h3>
      <p>
        По отдельности числа вектора ничего не значат. Смысл в том, как векторы расположены относительно друг друга. При обучении модель
        сдвигает строки таблицы так, чтобы токены из похожих контекстов получили похожие векторы. Похожесть обычно меряют углом между векторами
        (косинусная близость): чем меньше угол, тем ближе смысл.
      </p>
      <p>
        Представить {fmt.int(m.hidden)} измерений нельзя, но можно нарисовать идею в двух. Где на такой карте окажется слово, у которого
        несколько значений?
      </p>

      <MeaningMapFigure />

      <p>
        Полезная модель в голове: эмбеддинг это стартовая точка токена. Он одинаков для дверного ключа и для ключа-родника. Различать смыслы
        будут следующие шаги: <Term t="Attention">attention</Term> подмешивает к вектору информацию от предыдущих токенов, и вектор
        постепенно сдвигается. Такой уточнённый вектор между слоями называют <Term t="hidden state" />.
      </p>

      <Callout kind="pitfall" title="эмбеддинг не знает ни контекста, ни порядка">
        <p>
          Для таблицы фразы «мать любит дочь» и «дочь любит мать» почти неотличимы: те же слова дают те же строки, а порядка таблица не видит.
          Кто кого любит, модель узнаёт позже: позицию добавляет RoPE, а связи между словами строит attention (<ChapterLink to="attention" />
          ). Поэтому эмбеддинг одного токена ещё не «смысл слова в предложении».
        </p>
      </Callout>

      <Deeper title="позиция токена и RoPE">
        <p>
          Таблица не знает порядка токенов. В оригинальном трансформере 2017 года к эмбеддингу прибавляли отдельный вектор позиции. Современные
          модели, включая Qwen3 и Llama, делают иначе: внутри каждого слоя attention они поворачивают векторы{' '}
          <Term t="Q / K / V">query и key</Term> на угол, пропорциональный позиции. Это <Term t="RoPE" /> (rotary position embedding).
        </p>
        <p>
          Вектор одной головы attention (голов в слое несколько, о них в главе <ChapterLink to="attention" />; у {m.name} в голове{' '}
          {fmt.int(m.headDim)} {fmt.plural(m.headDim, ['число', 'числа', 'чисел'])}) делят на {m.headDim / 2}{' '}
          {fmt.plural(m.headDim / 2, ['пару', 'пары', 'пар'])}, и каждая пара это точка на плоскости. Пару
          номер i у токена на позиции m поворачивают на угол m·θᵢ. Частоты θᵢ = base<sup>−2i/d</sup> не обучаются: их задаёт{' '}
          <code>rope_theta</code> в config (у Qwen3 это {fmt.int(1_000_000)}). Первые пары крутятся быстро, последние почти стоят на месте.
        </p>
        <p>Почему поворот кодирует именно расстояние между токенами? Посмотрите на одну пару координат.</p>
        <RopeFigure />
        <p>
          Поворот на mθ и поворот на nθ вместе дают поворот на разность углов, поэтому скалярное произведение после RoPE зависит только от n −
          m:
        </p>
        <Formula block tex="\left(R_{m\theta}\,\cq{q}\right)^{\top}\left(R_{n\theta}\,\ck{k}\right)=\cq{q}^{\top}R_{(n-m)\theta}\,\ck{k}" label="R: матрица поворота на угол; из q·k attention считает вес" />
        <p>
          Attention считает веса как раз из q·k, поэтому модель видит, насколько далеко стоят токены, а не их абсолютные номера. Обучаются не
          повороты, а матрицы W_Q и W_K, которые учатся этими поворотами пользоваться.
        </p>
        <Callout kind="production" title="RoPE и кэш">
          <p>
            В <Term t="KV cache" /> ключи кладутся уже повёрнутыми, то есть привязанными к своим позициям; векторы V не поворачиваются. Поэтому
            готовый кусок кэша нельзя просто перенести на другое место промпта. Но главная причина, по которой кэш переиспользуется только при
            точном совпадении начала, другая: начиная со второго слоя (в первый приходят чистые эмбеддинги) K и V каждого токена считаются из
            его hidden state, а в нём уже смешаны все предыдущие токены (<ChapterLink to="prefix-caching" />
            ).
          </p>
        </Callout>
      </Deeper>

      <Takeaways
        items={[
          <>
            ID токена выбирает строку таблицы эмбеддингов: это чтение памяти, а не вычисление. Промпт из N токенов превращается в матрицу N ×
            d_model.
          </>,
          <>
            У {m.name} таблица {fmt.int(m.vocab)} × {fmt.int(m.hidden)}: около {fmt.compact(tableParams)} параметров и {fmt.bytes(tableBytes)} в
            BF16. Строк больше, чем токенов в токенизаторе ({fmt.int(QWEN3_TOKENIZER_SIZE)}): хвост добит до удобного размера.
          </>,
          <>
            Один и тот же токен всегда даёт один и тот же вектор. Позицию добавляет RoPE внутри attention, а смысл в контексте собирают слои
            трансформера.
          </>,
        ]}
      />
    </Chapter>
  )
}
