import { getModel, slidingLayers } from '@/engine/data/models'
import { getGpu } from '@/engine/data/gpus'
import { attentionFlopsPerPair, fitsCheck, kvBytesPerToken, kvLayout, prefillFlopsBreakdown, weightBytes } from '@/engine/perf'
import { Callout, Chapter, ChapterLink, Deeper, Formula, SimulatorLink, Takeaways, Term, fmt } from '@/ui'
import { CacheVsNoCache } from './CacheVsNoCache'
import { KvAnatomy } from './KvAnatomy'
import { KvPerTokenBars, SlidingWindowChart } from './KvDeeper'
import { MemoryCalculator } from './MemoryCalculator'

// Канонический пример главы: Qwen3-8B в BF16 на одной H100 (числа считает движок).
const QWEN = getModel('qwen3-8b')
const H100 = getGpu('h100-sxm')
const PER_TOKEN = kvBytesPerToken(QWEN) // 147 456
const SEQ_8K = 8192 * PER_TOKEN
const WEIGHTS = weightBytes(QWEN)
const FIT_8K = fitsCheck(QWEN, H100, { contextLen: 8192, seqs: 32, memUtil: 0.92 })
// Где attention на шаге decode догоняет умножение на веса по числу операций: линейные слои на один токен
// против attention нового токена на каждый токен контекста (во всех полных слоях).
const DECODE_LINEAR_FLOPS = prefillFlopsBreakdown(QWEN, 1).linear
const ATTN_FLOPS_PER_CTX = attentionFlopsPerPair(QWEN, 'decode') * kvLayout(QWEN).fullLayers
const ATTN_PARITY = DECODE_LINEAR_FLOPS / ATTN_FLOPS_PER_CTX
const DSV3 = getModel('deepseek-v3')
const GPT_OSS = getModel('gpt-oss-120b')

export default function KvCacheChapter() {
  return (
    <Chapter
      id="kv-cache"
      lead={
        <>
          Чтобы на каждом шаге decode не пересчитывать прошлое, модель хранит векторы K и V каждого прочитанного токена в каждом слое. Это
          и есть KV cache: он экономит огромный объём вычислений, но занимает память GPU и растёт с длиной контекста и числом одновременных
          запросов.
        </>
      }
    >
      <h3>Зачем вообще что-то кэшировать</h3>
      <p>
        Вспомним <ChapterLink to="attention">attention</ChapterLink>. Новый токен сравнивает свой Query с Key всех предыдущих токенов и
        собирает их Value. А вот Key и Value старых токенов от нового токена не зависят: маска запрещает смотреть вперёд, поэтому на
        каждом шаге они получаются ровно такими же, как на предыдущем.
      </p>
      <p>
        Значит, их можно посчитать один раз и сохранить. Так и делают: <Term t="KV cache" /> строится на <Term t="Prefill">prefill</Term> и
        дописывается на каждом шаге <Term t="Decode">decode</Term>. Новый токен добавляет свои K и V в каждый слой и читает из кэша K и V всех
        предыдущих. Query прошлых токенов больше никому не нужны, поэтому кэшируют только K и V, отсюда и название.
      </p>
      <p>
        Без кэша всё гораздо хуже, чем кажется. Чтобы получить K и V старого токена в двадцатом слое, нужно его скрытое состояние после
        девятнадцатого, а для этого восемнадцатый, и так до самого начала. Поэтому без кэша каждый шаг decode превращается в новый
        prefill всей последовательности. Насколько это дорого?
      </p>

      <CacheVsNoCache />

      <p>
        Что заметить. Без кэша работа на шаг растёт вместе с длиной последовательности, а сумма за всю генерацию растёт как квадрат. С
        кэшем каждый шаг стоит почти одинаково: один токен проходит через модель, а attention читает готовые K и V. Сумма растёт почти
        линейно. «Почти», потому что новый токен всё равно сравнивается со всеми прошлыми ключами. При контексте в пару тысяч токенов
        это малая доля шага, но доля растёт с длиной: у Qwen3-8B при контексте около {fmt.compact(ATTN_PARITY, 0)} токенов attention
        по числу операций догоняет умножение на веса.
      </p>
      <p>
        По времени разница меньше, чем по FLOP. Шаг decode с кэшем всё равно читает из памяти все веса, и это занимает миллисекунды,
        даже когда считать почти нечего. А пока последовательность короткая, пересчёт без кэша прячется за тем же чтением (это разбирали
        в главе <ChapterLink to="roofline">про compute- и memory-bound</ChapterLink>). Но с ростом контекста разрыв быстро растёт, и на
        длинных диалогах генерация без кэша стала бы невозможной. Поэтому KV cache включён во всех движках по умолчанию, отключать его
        никто не предлагает.
      </p>

      <Callout kind="intuition" title="конспект на рабочем столе">
        <p>
          Модель читает промпт и делает конспект: по записи на каждый токен в каждом слое. Отвечая, она сверяется с конспектом, а не
          перечитывает задание перед каждым словом. Подвох в том, что конспект лежит на маленьком и очень дорогом столе (память GPU), и
          у каждого одновременного разговора свой конспект.
        </p>
      </Callout>

      <h3>Что именно лежит в кэше</h3>
      <p>
        Для каждого токена, в каждом слое, хранятся K и V по каждой KV-голове. KV-голов обычно меньше, чем голов Query: в{' '}
        <Term t="GQA" /> несколько Query-голов делят одну пару K и V. У Qwen3-8B 32 головы Query и всего 8 KV-голов. Каждая голова это
        вектор из 128 чисел, каждое число в BF16 занимает 2 байта. Перемножаем:
      </p>
      <Formula
        block
        className="max-sm:text-[14px]"
        tex={`\\begin{aligned}\\text{KV на токен} &= 2 \\cdot \\text{слои} \\cdot \\text{KV-головы} \\cdot d_{head} \\cdot \\text{байт}\\\\ &= 2 \\cdot 36 \\cdot 8 \\cdot 128 \\cdot 2 = ${PER_TOKEN.toLocaleString('en-US').replace(/,/g, '\\,')}\\ \\text{${fmt.plural(PER_TOKEN, ['байт', 'байта', 'байт'])}}\\end{aligned}`}
        label={`Qwen3-8B, BF16: ${fmt.bytes(PER_TOKEN, { mode: 'binary' })} на каждый токен контекста`}
      />
      <p>Двойка в начале означает K и V. Ниже та же формула в виде картинки: строка решётки это слой, клетка это вектор одной головы.</p>

      <KvAnatomy />

      <p>
        {fmt.bytes(PER_TOKEN, { mode: 'binary' })} на токен кажутся мелочью, пока не умножишь на длину. Один разговор на 8 192 токена
        у Qwen3-8B занимает {fmt.bytes(SEQ_8K)} KV, а 32 таких разговора одновременно уже {fmt.bytes(32 * SEQ_8K)}: больше чем вдвое
        тяжелее самих весов модели ({fmt.bytes(WEIGHTS)}).
      </p>

      <Callout kind="precise">
        <p>
          KV одной последовательности = KV на токен × (токены промпта + сгенерированные токены). Рост линейный: каждый новый токен
          добавляет ровно {fmt.bytes(PER_TOKEN, { mode: 'binary' })}. Квадратичной остаётся работа attention (пары «токен смотрит на
          токен»): на prefill по длине промпта, а за всю генерацию в сумме по длине ответа, потому что каждый шаг читает все прошлые
          ключи. Память под кэш растёт линейно.
        </p>
      </Callout>

      <h3>Сколько это весит на GPU</h3>
      <p>
        Память GPU делится на четыре части: веса модели (их размер фиксирован), рабочая память прохода (активации, CUDA graphs),
        пул KV и небольшая доля, которую движок не трогает. Всё, что осталось после весов и активаций, уходит в пул KV. Его размер
        решает, сколько последовательностей обслуживается одновременно, то есть какой будет <Term t="батч">batch</Term> и throughput
        (подробнее в главе <ChapterLink to="batching">про continuous batching</ChapterLink>).
      </p>
      <p>
        Сколько одновременных разговоров выдержит одна{' '}
        <Term t="Hopper (H100 / H200)">H100</Term> с Qwen3-8B? Модель и GPU калькулятор берёт из симулятора, пока вы не выберете в нём
        свои.
      </p>

      <MemoryCalculator />

      <p>
        Главное правило читается прямо с кривой: последовательности × длина контекста ≈ размер пула. Вдвое короче контекст, вдвое больше
        разговоров. На одной H100 с Qwen3-8B в BF16 помещается {fmt.int(FIT_8K.maxSeqs)} последовательностей по 8 192 токена. FP8 KV
        удваивает это число, а модель на 70 миллиардов параметров на одной такой GPU вообще не оставляет места под кэш. Книга советует
        закладывать память под веса и ещё хотя бы половину их объёма под KV, а для длинного контекста и большого batch больше.
      </p>
      <p>
        У кэша есть и вторая цена, не только место. Каждый шаг decode читает KV всех последовательностей batch целиком: те же 32
        разговора по 8 192 токена это {fmt.bytes(32 * SEQ_8K)} чтения на каждом шаге, больше, чем сами веса ({fmt.bytes(WEIGHTS)}).
        Поэтому длинный контекст замедляет печать токенов, даже когда память ещё есть (глава{' '}
        <ChapterLink to="roofline">про compute- и memory-bound</ChapterLink>).
      </p>

      <Callout kind="production" title="gpu_memory_utilization, пул KV, preemption, max_model_len">
        <ul>
          <li>
            <code>--gpu-memory-utilization</code> в <Term t="vLLM" /> задаёт долю всей памяти GPU, которую берёт движок: веса,
            активации и <Term t="gpu_memory_utilization">пул KV</Term> вместе. По умолчанию 0,9 (по v0.19 включительно) и 0,92 начиная с
            v0.20.
            При старте vLLM прогоняет пробный проход, меряет пик активаций и сразу отдаёт весь остаток бюджета под пул. В логе это строка{' '}
            <code>GPU KV cache size: N tokens, Maximum concurrency for M tokens per request: X.XXx</code> (до v0.28 это были две строки).
          </li>
          <li>
            <code>--max-model-len</code> (<Term t="max_model_len">максимальная длина</Term> последовательности) ставьте по реальной
            потребности, а не по максимуму модели. Если в пул не влезает даже одна последовательность такой длины, движок не стартует и
            предложит поднять gpu_memory_utilization или уменьшить max_model_len.
          </li>
          <li>
            Если блоки KV кончились посреди генерации, планировщик вытесняет последний принятый запрос (<Term t="Preemption" />): его
            кэш освобождается, запрос встаёт в начало очереди и потом пересчитывается заново. В vLLM V1 других вариантов нет: режим
            swap, когда KV вытесненного запроса уезжал в RAM, был только в старом движке V0 (оставшийся от него параметр{' '}
            <code>swap_space</code> удалён в v0.18). Не путайте с оффлоадом prefix cache в RAM: он в vLLM есть, о нём глава{' '}
            <ChapterLink to="kv-tiers">про иерархию KV cache</ChapterLink>. Частые вытеснения видны в метрике{' '}
            <code>vllm:num_preemptions</code>: помогают FP8 KV, меньший <code>max_num_seqs</code> или больше GPU.
          </li>
          <li>
            У других движков та же ручка значит другое: в TensorRT-LLM <code>free_gpu_memory_fraction</code> это доля свободной памяти
            после загрузки весов (по умолчанию 0,9), в SGLang <code>mem_fraction_static</code> это доля под веса и пул KV вместе.
          </li>
        </ul>
      </Callout>

      <Callout kind="pitfall" title="nvidia-smi показывает 92 % сразу после старта">
        <p>
          Это не утечка. Движок заранее забирает пул KV целиком, даже если запросов ещё нет: так он не тратит время на выделение памяти
          во время работы. Смотреть надо не на память GPU, а на заполненность пула: в vLLM это <code>vllm:kv_cache_usage_perc</code>.
        </p>
      </Callout>

      <SimulatorLink stage="decode">Растущий KV cache на шагах decode в симуляторе</SimulatorLink>

      <Deeper title="GQA, MQA, MLA, FP8 KV и скользящее окно">
        <h4>Меньше голов K и V</h4>
        <p>
          В классическом multi-head attention у каждой головы Query своя пара K и V. <Term t="MQA" /> оставляет одну пару K и V на все
          головы, <Term t="GQA" /> делит головы на группы. Кэш уменьшается во столько раз, во сколько KV-голов меньше, чем Query-голов:
          у Qwen3-8B в 4 раза, у Qwen3-235B-A22B в 16. Качество при этом почти как у MHA, потому что модель так и обучали.
        </p>
        <p>
          <Term t="MLA" /> из DeepSeek идёт дальше: в кэше лежит один сжатый вектор на слой ({DSV3.kvLoraRank ?? 512} чисел) плюс
          небольшой ключ для позиций ({DSV3.qkRopeHeadDim ?? 64} числа). Получается {fmt.bytes(kvBytesPerToken(DSV3), { mode: 'binary' })}{' '}
          на токен у модели на 671 миллиард параметров, меньше, чем у Llama-3.1-8B. Те же числа на одном графике, всё в BF16; бледные
          столбики это гипотетические версии Qwen3-8B:
        </p>
        <KvPerTokenBars />
        <h4>FP8 KV</h4>
        <p>
          <Term t="FP8 KV cache">KV можно хранить в FP8</Term> отдельно от формата весов: <code>--kv-cache-dtype fp8</code> в vLLM (в SGLang{' '}
          <code>fp8_e4m3</code> или <code>fp8_e5m2</code>). Байт на число вдвое меньше, значит вдвое больше последовательностей в том же пуле и вдвое меньше данных на чтение в
          каждом шаге decode. Цена: небольшая ошибка округления в attention, которую проверяют на своих задачах. Сжатый KV ещё и быстрее
          переносится между машинами и уровнями памяти, это пригодится в главе <ChapterLink to="kv-tiers">про иерархию KV cache</ChapterLink>.
        </p>
        <h4>Скользящее окно</h4>
        <p>
          В части слоёв некоторых моделей токен смотрит только на последние W токенов. У gpt-oss-120b{' '}
          {slidingLayers(GPT_OSS)} слоёв из {GPT_OSS.layers} со скользящим окном в {GPT_OSS.slidingWindow?.window ?? 128} токенов, у
          Gemma 3 пять локальных слоёв на один глобальный. Такие слои хранят не больше W токенов, поэтому у gpt-oss KV последовательности
          растёт вдвое медленнее:
        </p>
        <SlidingWindowChart />
        <p>
          Экономия появляется, только если движок умеет держать разные слои по-разному (в vLLM это гибридный менеджер KV cache).
          Коннекторы KV, которые его не поддерживают, отключают гибридный режим, и модель снова тратит память как будто все слои
          полные.
        </p>
      </Deeper>

      <Takeaways
        items={[
          <>KV cache хранит K и V каждого токена в каждом слое, чтобы шаг decode считал только новый токен. Без него каждый шаг был бы новым prefill всей последовательности.</>,
          <>
            Размер на токен: 2 × слои × KV-головы × head_dim × байт. У Qwen3-8B в BF16 это {fmt.bytes(PER_TOKEN, { mode: 'binary' })}, а
            кэш растёт линейно с длиной контекста и числом одновременных последовательностей.
          </>,
          <>После весов почти вся память GPU уходит в пул KV. Пул решает, сколько запросов обслуживается одновременно, а значит и throughput.</>,
          <>Рычаги: архитектура (GQA, MLA), FP8 KV, честный max_model_len, больше GPU. Когда пул всё же кончается, движок вытесняет запросы.</>,
        ]}
      />
    </Chapter>
  )
}
