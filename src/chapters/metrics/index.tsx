import { useMemo } from 'react'
import { Callout, Chapter, ChapterLink, CodeBlock, Deeper, SimulatorLink, Takeaways, Term, fmt } from '@/ui'
import { useHardwareState } from '@/chapters/prefill-decode/shared/hardware'
import { usePromptTokens } from '@/chapters/prefill-decode/shared/prompt'
import { GoodputFigure } from './Goodput'
import { MeasureTimelineFigure } from './MeasureTimeline'
import { TtftHistogramFigure, queueCurve } from './TtftHistogram'
import { WideFormula } from '@/chapters/prefill-decode/shared/WideFormula'

const PROMQL = 'histogram_quantile(0.99,\n  sum by (le) (rate(vllm:time_to_first_token_seconds_bucket[5m])))'

export default function MetricsChapter() {
  const { hw } = useHardwareState()
  const prompt = usePromptTokens()
  const promptLen = prompt.tokens?.length ?? 43
  const curve = useMemo(() => queueCurve(hw), [hw])
  const at = (rho: number) => curve.find((c) => Math.abs(c.rho - rho) < 1e-9) ?? curve[0]
  const q50 = at(0.5)
  const q90 = at(0.9)

  return (
    <Chapter
      id="metrics"
      lead={
        <>
          Как понять, быстрый ли сервис? Пользователь чувствует две вещи: сколько ждать первого слова и как быстро печатается ответ. Бизнес считает,
          сколько токенов в секунду выдаёт весь парк GPU и сколько запросов уложились в обещанные задержки. Это TTFT, ITL, throughput и goodput, и смотрят
          на них перцентилями, а не средним.
        </>
      }
    >
      <h3>Четыре числа одного запроса</h3>
      <p>
        Две фазы генерации из главы <ChapterLink to="prefill-decode" /> дают два главных ощущения пользователя. Вокруг них строятся все метрики
        латентности:
      </p>
      <ul>
        <li>
          <Term t="TTFT" /> (time to first token): от отправки запроса до первого токена ответа. Это очередь, prefill и сеть. Отвечает за ощущение
          отзывчивости.
        </li>
        <li>
          <Term t="ITL" /> (inter-token latency): пауза между двумя соседними токенами, в основном это шаг decode. ITL 10 мс означает 100 токенов в
          секунду для одного пользователя.
        </li>
        <li>
          <Term t="TPOT" /> (time per output token): средний интервал на токен в одном запросе, (E2E − TTFT) / (N − 1). Одно число на запрос, удобное
          для целей и отчётов.
        </li>
        <li>
          <Term t="E2E latency">E2E</Term> (end-to-end): от отправки до последнего токена. Для агентов и tool calls важно только оно: промежуточные токены
          никто не читает.
        </li>
      </ul>
      <WideFormula tex="\text{E2E} = \cprefill{\text{TTFT}} + \cdecode{\text{TPOT}} \cdot (N - 1)" label="N: токенов в ответе" />
      <p>
        Вопрос в том, где ставить отметки времени. Сервер видит свою часть: от прихода запроса до выдачи токенов. Клиент видит больше: сеть в обе
        стороны, и токены приходят к нему пачками, чанками потока <Term t="SSE" />. Сравним обе картины на одном запросе.
      </p>

      <MeasureTimelineFigure hw={hw} promptLen={promptLen} />

      <p>
        Что заметить. TTFT клиента больше серверного на сеть туда и обратно. Размер чанка не меняет ни TTFT, ни TPOT: vLLM и SGLang отправляют первый
        токен сразу, не дожидаясь полного чанка, а последний чанк уходит вместе с последним токеном. Растут только интервалы между чанками: тот, кто
        считает ITL по чанкам, увидит печать рывками, которой на сервере не было. Поэтому у каждой метрики нужно знать не только название, но и
        формулу, и точку измерения. <SimulatorLink stage="stream" />
      </p>

      <Callout kind="precise" title="ITL и TPOT в разных инструментах">
        В <code>vllm bench serve</code> ITL это список интервалов между чанками всех запросов, а TPOT считается по каждому запросу как (E2E − TTFT) / (N −
        1). NVIDIA AIPerf называет ITL именно вторую величину и прямо пишет, что это TPOT. Книга называет ITL время между соседними токенами. Сравнивать
        цифры из разных инструментов можно только после того, как сверили формулы.
      </Callout>

      <h3>Throughput: на пользователя и на весь сервис</h3>
      <p>
        Скорость, которую чувствует человек, это <Term t="TPS">токены в секунду</Term> на пользователя, примерно 1000 / ITL. Ёмкость сервиса это{' '}
        <Term t="throughput" />: сколько токенов в секунду выдают все запросы вместе или сколько запросов в секунду сервис завершает. Эти числа тянут в
        разные стороны. Больший <Term t="batch" /> поднимает общий throughput и замедляет каждого пользователя, как мы видели в главе <ChapterLink to="roofline" />.
        Обычно оптимизируют одно при ограничении на другое: максимум throughput при заданной скорости печати.
      </p>

      <h3>Перцентили: среднее врёт</h3>
      <p>
        Время ответа LLM распределено с длинным правым хвостом: большинство запросов быстрые, но редкие идут в разы дольше. Пример: 20 замеров TTFT,
        18 из них от 180 до 420 мс и два выброса, 900 мс и 2 400 мс. Среднее 382 мс, медиана 228 мс: два запроса из двадцати сдвинули среднее на 58 %.
        Среднее не описывает ни быстрых, ни медленных.
      </p>
      <p>
        Поэтому латентность описывают <Term t="перцентили">перцентилями</Term>. p50, медиана: половина запросов быстрее. p90: медленнее только каждый
        десятый. p99: каждый сотый. Пользователь запоминает именно медленные ответы, а у сервиса с тысячами запросов в минуту «каждый сотый» случается
        десятки раз в минуту. Что происходит с хвостом, когда сервис нагружается?
      </p>

      <TtftHistogramFigure hw={hw} curve={curve} />

      <p>
        Что заметить. При загрузке 50 % медиана TTFT {fmt.ms(q50.p50)}, p99 {fmt.ms(q50.p99)}. При 90 % медиана {fmt.ms(q90.p50)}, а p99 уже{' '}
        {fmt.ms(q90.p99)}: запросы приходят случайно, и чем меньше запаса, тем дольше рассасываются случайные пачки. Это «хоккейная клюшка» любой
        очереди: от 50 до 90 % загрузки задержка растёт в разы, ближе к 100 % уходит вверх. Поэтому автоскейлеры целятся в 60-70 % загрузки, а не в 100 %
        (глава <ChapterLink to="production" />).
      </p>

      <h3>Throughput против латентности и goodput</h3>
      <p>
        Нагрузку удобно мерить через <Term t="concurrency" />: сколько запросов одновременно в работе. Так её задают и бенчмарки (
        <code>vllm bench serve --max-concurrency</code>), и автоскейлеры. Пока GPU не насыщен, рост concurrency почти бесплатно поднимает throughput:
        шаг decode читает веса один раз на весь batch. Но каждый следующий запрос добавляет в шаг свой KV и свой prefill, поэтому шаг удлиняется, и все
        пользователи печатают медленнее.
      </p>
      <p>
        Рабочую точку выбирают по <Term t="service level objective">SLO</Term>: внутренним целям по задержкам, например TTFT не больше 450 мс и TPOT
        не больше 40 мс (пороги MLPerf для интерактивного режима, с них и стартует фигура ниже). <Term t="goodput" /> считает только запросы, уложившиеся во все SLO сразу. Его максимум и есть честная ёмкость сервиса: дальше
        throughput ещё растёт, но обслуживать так никто не обещал. Где эта точка для {hw.model.name} на {hw.gpu.name}?
      </p>

      <GoodputFigure hw={hw} />

      <p>
        Что заметить. Каждое удвоение concurrency сначала почти удваивает throughput, потом прибавка тает: чем больше запросов в работе, тем чаще в
        шаги decode подмешивается prefill новых запросов (промпты здесь в пять раз длиннее ответов) и тем больше KV читает каждый шаг. TPOT при этом
        растёт на каждом уровне. Goodput идёт вместе с throughput, пока TPOT и TTFT в пределах SLO, а потом падает почти до нуля: запросов
        обслуживается много, но обещанной скорости не получает почти никто. Чем жёстче SLO, тем меньше пользователей на один GPU и тем больше GPU нужно на
        тот же трафик. Если держать и TTFT, и ITL на одних GPU не выходит, фазы разносят по разным пулам (глава <ChapterLink to="disaggregation" />
        ).
      </p>
      <p>
        В этой симуляции ожидание у клиента в TTFT не входит: concurrency ограничивает сам клиент. Если же запросы приходят быстрее, чем сервис их
        обрабатывает, они копятся в очереди сервера, и TTFT уходит в секунды, как в предыдущей фигуре. Поэтому в проде concurrency ограничивают на входе
        (gateway, admission control) и при росте трафика добавляют реплики (autoscaler), а не надеются, что очередь рассосётся сама.
      </p>

      <Callout kind="production" title="что мониторить и какие SLO ставить">
        <p>
          Движки отдают метрики в формате Prometheus на <code>/metrics</code>. В vLLM главные: <code>vllm:time_to_first_token_seconds</code>,{' '}
          <code>vllm:inter_token_latency_seconds</code>, <code>vllm:request_time_per_output_token_seconds</code>,{' '}
          <code>vllm:e2e_request_latency_seconds</code> (гистограммы латентности), <code>vllm:request_queue_time_seconds</code> (ожидание),{' '}
          <code>vllm:num_requests_running</code> и <code>vllm:num_requests_waiting</code> (batch и очередь), <code>vllm:kv_cache_usage_perc</code>{' '}
          (заполненность KV), <code>vllm:prefix_cache_hits</code> и <code>vllm:prefix_cache_queries</code> (hit rate),{' '}
          <code>vllm:num_preemptions</code>. Frontend Dynamo пишет <code>dynamo_frontend_time_to_first_token_seconds</code> и{' '}
          <code>dynamo_frontend_inter_token_latency_seconds</code>. Имена меняются между версиями, у счётчиков в выдаче бывает суффикс{' '}
          <code>_total</code>.
        </p>
        <p>Перцентиль по всем репликам считают из гистограмм, а не усредняют готовые p99:</p>
        <CodeBlock lang="text" code={PROMQL} title="PromQL: p99 TTFT по всем репликам" />
        <p>Примеры SLO (ориентиры, не стандарт):</p>
        <ul>
          <li>
            Чат: TTFT p90 до 500 мс, ITL до 50 мс, то есть от 20 ток/с, что быстрее чтения. Такие цели стоят по умолчанию в <Term t="Planner" /> у
            Dynamo для режима sla (в режиме по умолчанию он смотрит на очередь и заполненность KV); в MLPerf для интерактивного режима Llama-2-70B: TTFT
            до 450 мс и TPOT до 40 мс по p99.
          </li>
          <li>
            Автодополнение кода: важен весь короткий ответ, например E2E p95 до 300 мс. Промпты длинные (контекст файла), ответы короткие: упор в
            prefill и TTFT.
          </li>
          <li>
            Агенты: одно действие пользователя запускает десятки вызовов подряд, и хвосты складываются. Если каждый вызов с вероятностью 1 % медленнее
            своего p99, то при 10 вызовах в хвост попадает каждое десятое действие (1 − 0,99¹⁰ ≈ 10 %). Поэтому у агентов p99 одного вызова мало:
            смотрят более глубокий хвост (p99,9) и E2E всего действия.
          </li>
          <li>Офлайн-обработка: латентность почти не важна, оптимизируют throughput и цену токена.</li>
        </ul>
      </Callout>

      <Callout kind="pitfall" title="как испортить замеры на клиенте">
        <ul>
          <li>TTFT клиента включает сеть, TLS и gateway. Его нельзя сравнивать с серверной гистограммой: это разные величины.</li>
          <li>
            Первый SSE-чанк часто несёт только роль ассистента и пустой текст. Если считать TTFT по нему, сервис покажется быстрее; vLLM bench и AIPerf
            такие чанки пропускают.
          </li>
          <li>Чанк не равен токену: в одном чанке бывает несколько токенов. Интервалы между чанками дают рваный ITL, надёжнее TPOT.</li>
          <li>p99 на маленькой выборке это почти максимум. Для осмысленного p99 нужны сотни и тысячи запросов.</li>
          <li>
            Нагрузочный тест на случайном тексте врёт: prefix cache и speculative decoding ведут себя на нём не так, как на настоящих промптах. Берите
            реалистичные данные и пуассоновские приходы, а не «всё сразу».
          </li>
        </ul>
      </Callout>

      <Deeper title="закон Литтла, методы перцентилей, гистограммы Prometheus">
        <h4>Закон Литтла</h4>
        <p>
          Средняя concurrency = интенсивность запросов × среднее время жизни запроса (L = λ · W). Если приходит 10 запросов в секунду, а запрос живёт
          10,5 с (TTFT 0,5 с плюс 500 токенов по 20 мс), одновременно в работе в среднем 105 запросов. Так из трафика и E2E прикидывают, сколько слотов в
          batch и сколько реплик нужно. В фигуре с goodput concurrency задаёт сам клиент, а при открытом потоке запросов её оценивают именно так.
        </p>
        <h4>Как считают перцентиль</h4>
        <p>
          Есть два распространённых метода. Nearest-rank берёт элемент с номером ⌈p · n⌉ из отсортированной выборки. Линейная интерполяция (по умолчанию
          в numpy) берёт точку между соседними элементами. На 20 замерах из примера выше p90 выходит 420 мс одним способом и 468 мс другим. p99 по
          nearest-rank просто равен максимуму (2 400 мс), интерполяция даёт 2 115 мс: оба числа определяются одним-двумя самыми медленными замерами. На
          больших выборках методы сходятся.
        </p>
        <h4>Гистограммы и агрегация</h4>
        <p>
          Серверные метрики латентности хранят гистограммы с бакетами, и <code>histogram_quantile</code> интерполирует внутри бакета. Ошибка ограничена
          шириной бакета: всплеск на 220 мс в бакете 200-300 мс может показаться как 295 мс. Усреднять p99 разных реплик бессмысленно: складывают
          гистограммы и только потом берут квантиль, как в запросе PromQL выше.
        </p>
        <h4>Что ещё мерить рядом с латентностью</h4>
        <p>
          Латентность сама по себе не объясняет причину. Рядом нужны: число запросов, длины входа и выхода (<Term t="ISL / OSL">ISL и OSL</Term>), коды ответов, число реплик,
          загрузка GPU и памяти, глубина очереди. Рост TTFT при ровном трафике и длинных промптах означает одно, при всплеске запросов другое. Метрика
          «GPU utilization» из <code>nvidia-smi</code> здесь почти бесполезна: она показывает, исполнялось ли на GPU хоть одно{' '}
          <Term t="kernel">ядро</Term> (kernel, программа на GPU), а не насколько загружены вычислители (глава <ChapterLink to="roofline" />
          ).
        </p>
      </Deeper>

      <Takeaways
        items={[
          <>
            TTFT, ITL, TPOT и E2E = TTFT + TPOT × (N − 1). ITL и TPOT в разных инструментах называют по-разному, поэтому у каждой метрики важны формула и
            точка измерения: клиент и сервер видят разное.
          </>,
          <>Скорость на пользователя и общий throughput тянут в разные стороны: больший batch поднимает второй ценой первого.</>,
          <>Латентность описывают перцентилями p50, p90, p99. Когда загрузка приближается к 100 %, хвост растёт намного быстрее медианы.</>,
          <>Goodput считает только запросы, уложившиеся во все SLO. Рабочая точка сервиса там, где максимален goodput, а не throughput.</>,
        ]}
      />
    </Chapter>
  )
}
