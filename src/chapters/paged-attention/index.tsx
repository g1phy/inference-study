import { getModel } from '@/engine/data/models'
import { getGpu } from '@/engine/data/gpus'
import { DEFAULT_BLOCK_SIZE } from '@/engine/kv'
import { kvCapacityTokens, kvLayout } from '@/engine/perf'
import { Callout, Chapter, ChapterLink, Deeper, Formula, Takeaways, Term, fmt } from '@/ui'
import { AllocatorsFigure } from './AllocatorsFigure'
import { BlockTableFigure } from './BlockTableFigure'
import { CAPACITY, REQS } from './scenario'

const QWEN = getModel('qwen3-8b')
const H100 = getGpu('h100-sxm')
const LAYER_BLOCK = kvLayout(QWEN).bytesPerLayerPerToken * DEFAULT_BLOCK_SIZE // 64 КиБ
const FULL_BLOCK = LAYER_BLOCK * QWEN.layers // 2,25 МиБ
const POOL_TOKENS = kvCapacityTokens(QWEN, H100, { memUtil: 0.92 })
const POOL_BLOCKS = Math.floor(POOL_TOKENS / DEFAULT_BLOCK_SIZE)
// vLLM V1 печатает ёмкость целыми блоками: 25 494 × 16 = 407 904 токена (а не 407 915 из деления бюджета на байты токена)
const LOG_TOKENS = POOL_BLOCKS * DEFAULT_BLOCK_SIZE
// Числа сценария первой фигуры (первый подходящий кусок: A, B, C ложатся подряд с начала памяти).
const BOOK = (id: keyof typeof REQS) => REQS[id].prompt + REQS[id].maxTokens
const HOLE_A = BOOK('A')
const TAIL_HOLE = CAPACITY - BOOK('A') - BOOK('B') - BOOK('C')
const D_BOOK = BOOK('D')

export default function PagedAttentionChapter() {
  return (
    <Chapter
      id="paged-attention"
      lead={
        <>
          Если резервировать память под максимальную длину каждого запроса, большая часть KV cache стоит пустой. PagedAttention режет кэш
          на блоки фиксированного размера, выдаёт их по мере роста запроса и ведёт для каждого запроса таблицу блоков, как операционная
          система ведёт таблицу страниц памяти.
        </>
      }
    >
      <h3>Почему наивная схема теряет память</h3>
      <p>
        В прошлой главе мы выяснили, что <ChapterLink to="kv-cache">KV cache</ChapterLink> занимает почти всю свободную память GPU. Теперь
        вопрос, как эту память делить между запросами. Сервер не знает заранее, сколько токенов напишет модель: ответ может закончиться
        через 20 токенов, а может дойти до лимита <code>max_tokens</code>.
      </p>
      <p>
        До появления vLLM в 2023 году серверы обычно поступали просто: под каждый запрос сразу бронировали непрерывный кусок памяти на
        промпт плюс максимальный ответ. Непрерывный, потому что ядра attention ждали, что K и V одной последовательности лежат подряд. У такой схемы три вида
        потерь:
      </p>
      <ul>
        <li>
          <b>бронь на будущее</b>: слоты под ещё не написанные токены, сейчас пустые;
        </li>
        <li>
          <b>внутренняя фрагментация</b>: ответ закончился раньше лимита, и остаток брони так и не пригодился;
        </li>
        <li>
          <b>внешняя фрагментация</b>: между бронями разного размера остаются дыры. Свободной памяти в сумме хватает, но одним куском нет.
        </li>
      </ul>
      <p>
        Авторы vLLM измерили это на реальных запросах: в системах того времени под настоящие K и V уходило от 20 до 38 % памяти KV
        cache, остальное простаивало. С PagedAttention, о котором эта глава, vLLM поднял эту долю до 96 %.
      </p>

      <h3>Идея: память страницами, как в операционной системе</h3>
      <p>
        <Term t="PagedAttention" /> берёт приём из операционных систем. KV последовательности режется на{' '}
        <Term t="KV block (page)">блоки</Term> фиксированного размера, в <Term t="vLLM" /> по {DEFAULT_BLOCK_SIZE} токенов. Блоки лежат где
        угодно в памяти, а для каждого запроса ведётся таблица: логический блок 0 лежит в физическом блоке 12, логический 1 в физическом 3 и
        так далее. Новый блок выдаётся, только когда заполнен предыдущий, поэтому на запрос теряется не больше {DEFAULT_BLOCK_SIZE - 1}{' '}
        слотов последнего блока.
      </p>
      <p>
        Слово «attention» в названии не случайно: ядро attention научили читать K и V не подряд, а блок за блоком по этой таблице. Как это
        выглядит на одних и тех же запросах в двух схемах?
      </p>

      <AllocatorsFigure />

      <p>
        Что заметить. Слева заштрихована большая доля выделенной памяти: на первых шагах около трёх четвертей, к шагу 9 примерно половина.
        Это брони под ответы, которые ещё не написаны и, может быть, не будут написаны никогда. Когда A уходит, свободных дыр становится
        две: {HOLE_A} слотов на месте A и {TAIL_HOLE} в конце памяти, пустующих с прихода C. D просит промпт {REQS.D.prompt} плюс
        max_tokens {REQS.D.maxTokens}, то есть бронь на {D_BOOK} слотов подряд, и не помещается ни в одну дыру, хотя в сумме свободно
        ровно {HOLE_A + TAIL_HOLE}. E меньше и влез бы, но очередь FIFO: он стоит за D. Справа блоки разбросаны по памяти, штриховка есть
        только в хвосте последнего блока каждого запроса, и оба новых запроса сразу работают.
      </p>

      <Callout kind="intuition" title="гостиница">
        <p>
          Старая схема похожа на гостиницу, которая под каждого гостя бронирует целый этаж: вдруг приедет вся семья. PagedAttention выдаёт
          номера по одному, по мере заезда, в любом крыле. А список «гость → номера» хранится на ресепшене: это таблица блоков.
        </p>
      </Callout>

      <h3>Таблица блоков и общие блоки</h3>
      <p>
        Раз к блокам обращаются через таблицу, на один физический блок могут ссылаться несколько последовательностей. У каждого блока есть
        счётчик ссылок (ref count). В исходной схеме vLLM из статьи 2023 года последовательности делят блоки, пока совпадают, а когда одна
        из них пишет в общий блок, движок сначала делает его копию. Этот приём называется{' '}
        <Term t="Copy-on-write (CoW)">copy-on-write</Term>, его тоже придумали для операционных систем.
      </p>
      <p>
        Пример из статьи vLLM: запрос просит два варианта ответа (n = 2). Промпт общий, поэтому его KV не нужно хранить дважды. Что
        происходит с таблицами, когда ответы начинают расходиться?
      </p>

      <BlockTableFigure />

      <p>
        Общие блоки экономят память везде, где у последовательностей одинаковое начало. В статье vLLM parallel sampling (от 2 до 6
        вариантов ответа) сэкономил от 6 до 30 % памяти на разных наборах данных, а beam search, где ветки делят ещё и общую часть ответа,
        от 38 до 66 %.
      </p>

      <Callout kind="precise" title="как это устроено в нынешнем vLLM">
        <p>
          Так parallel sampling и beam search были устроены в статье vLLM и в его первых версиях. С осени 2024 года (v0.6.3 и v0.6.4) vLLM
          делает проще, и нынешний движок V1 тоже: запрос с n = 2 превращается в два обычных запроса с n = 1, и они делят только полные
          блоки промпта через <ChapterLink to="prefix-caching">prefix caching</ChapterLink> (он включён по умолчанию, это следующая глава),
          а неполный последний блок промпта и ответ у каждого свои. Beam search вынесен из движка: на каждом шаге каждая ветка уходит в
          движок отдельным запросом на один токен, а общее начало снова находится в prefix cache. Сама идея общих блоков со счётчиком ссылок
          осталась: на ней держится prefix caching, где общие блоки системного промпта делят уже разные запросы.
        </p>
      </Callout>

      <Callout kind="precise">
        <p>
          Блок это номер слота сразу во всех слоях: у каждого слоя свой тензор KV, а один номер блока указывает одну и ту же позицию в
          каждом из них. Адрес токена на позиции pos вычисляется по таблице:
        </p>
        <Formula
          block
          tex="\begin{aligned}\text{слот} &= \text{таблица}\left[\left\lfloor \tfrac{pos}{B} \right\rfloor\right] \cdot B\\ &\quad + (pos \bmod B)\end{aligned}"
        />
        <p>
          Один блок Qwen3-8B в BF16 весит {fmt.bytes(LAYER_BLOCK, { mode: 'binary' })} в каждом слое и {fmt.bytes(FULL_BLOCK, { mode: 'binary' })}{' '}
          по всем {QWEN.layers} слоям.
        </p>
      </Callout>

      <Callout kind="production" title="размер блока, число блоков, preemption">
        <ul>
          <li>
            <code>--block-size</code> в vLLM по умолчанию {DEFAULT_BLOCK_SIZE} во всех вышедших релизах; в основной ветке в ноябре 2026
            сменили на 64, но в релиз это ещё не попало. Некоторые ядра attention требуют свой размер (FlashMLA 64). У SGLang страница по
            умолчанию 1 токен, у TensorRT-LLM <code>tokens_per_block</code> 32.
          </li>
          <li>
            Сколько блоков получилось, движок пишет в лог при старте. Старые версии vLLM печатали <code># GPU blocks: N</code>, V1 пишет в
            токенах: <code>GPU KV cache size: N tokens</code>, это число блоков, умноженное на их размер. Для Qwen3-8B на H100 с
            gpu_memory_utilization 0,92 это примерно {fmt.tokens(LOG_TOKENS)}, то есть {fmt.int(POOL_BLOCKS)}{' '}
            {fmt.plural(POOL_BLOCKS, ['блок', 'блока', 'блоков'])} по {DEFAULT_BLOCK_SIZE}.
          </li>
          <li>
            Если для следующего токена нет свободного блока, планировщик вытесняет последний принятый запрос (
            <Term t="Preemption" />
            ): освобождает его блоки и ставит в начало очереди. Потом его промпт и уже написанный ответ пересчитаются одним prefill (в V1
            только так; swap в RAM был только в старом движке V0). Частые вытеснения видны в <code>vllm:num_preemptions</code>; лечат уменьшением{' '}
            <code>max_num_seqs</code>, FP8 KV или добавлением памяти. Подробнее о планировщике в главе <ChapterLink to="batching">про continuous batching</ChapterLink>.
          </li>
        </ul>
      </Callout>

      <Callout kind="pitfall" title="PagedAttention не ускоряет само ядро attention">
        <p>
          В микробенчмарках статьи ядро было на 20–26 % медленнее оптимизированного ядра FasterTransformer: ему приходится ходить по
          таблице. Выигрыш в другом: в ту же память помещается в несколько раз больше одновременных запросов, batch
          растёт, и throughput при той же задержке вырос в 2–4 раза.
        </p>
      </Callout>

      <Deeper title="почему блок 16 токенов, а не 1 и не 256">
        <p>
          Размер блока это компромисс. Маленький блок почти не теряет память, но ядру приходится чаще обращаться к таблице, и за одно
          обращение оно делает мало работы. Большой блок удобен GPU и переносу по сети, но хвост последнего блока пустует дольше, а prefix
          caching совпадает только целыми блоками: чем крупнее блок, тем реже совпадение. В статье vLLM лучшими оказались блоки от 16 до 128
          токенов на одних данных и 16–32 на других, по умолчанию выбрали 16.
        </p>
        <p>
          SGLang держит KV страницами по одному токену: его дерево префиксов (следующая глава) совпадает с точностью до токена. Системы,
          которые гоняют KV по сети, наоборот, укрупняют единицу хранения: LMCache по умолчанию режет кэш на куски по 256 токенов, потому что
          мелкие передачи плохо загружают канал (глава <ChapterLink to="kv-tiers">про иерархию KV cache</ChapterLink>).
        </p>
        <p>
          Ещё одна деталь vLLM V1: таблица блоков запроса только растёт, поэтому два одинаковых запроса в одном batch могут ненадолго
          держать два физических блока с одинаковым содержимым. Дубликат исчезает, когда запрос заканчивается.
        </p>
      </Deeper>

      <Takeaways
        items={[
          'Бронь под максимальную длину теряет большую часть памяти: пустые брони, недописанные хвосты и дыры между бронями разного размера.',
          <>
            PagedAttention хранит KV блоками по {DEFAULT_BLOCK_SIZE} токенов где угодно в памяти; таблица блоков связывает логические блоки
            с физическими, и потери не больше одного блока на запрос.
          </>,
          'Один физический блок могут делить несколько последовательностей (ref count): сегодня это прежде всего общий префикс разных запросов, а в статье vLLM так же, с copy-on-write, делили блоки parallel sampling и beam search.',
          'Выигрыш не в скорости ядра, а в том, что в ту же память помещается больше запросов: больше batch, выше throughput.',
        ]}
      />
    </Chapter>
  )
}
