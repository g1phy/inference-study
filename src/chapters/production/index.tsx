/** Пример закона Литтла на модели из симулятора: 10 запросов/с, промпт 1000, ответ 300 токенов, batch 32. */
function useLittle() {
  const [settings] = useSettings()
  return useMemo(() => {
    let m = findModel(settings.modelId) ?? getModel('qwen3-8b')
    const g = findGpu(settings.gpuId) ?? getGpu('h100-sxm')
    if (!fitsCheck(m, g, { contextLen: 1300, seqs: 32 }).fits) m = getModel('qwen3-8b')
    const ttft = prefillMs(m, g, 1000)
    const itl = decodeStepMs(m, g, { batch: 32, avgContext: 1150 })
    const W = (ttft + 299 * itl) / 1000
    const L = 10 * W
    const replicas = Math.ceil(L / (32 * 0.7))
    return { model: m.name, gpu: g.name, ttft, itl, W, L, replicas }
  }, [settings.modelId, settings.gpuId])
}

/** Условная цена часа H100 из примера книги (стр. 202), долларов. */
const GPU_HOUR_USD = 3.5
/** Доля памяти под движок как у vLLM по умолчанию с v0.20 (SPEC §8.8). */
const MEM_UTIL = 0.92

/** «7,2 доллара», «0,30 доллара»: для дробных сумм по-русски всегда «доллара». */
const usd = (x: number) => `${fmt.num(x, x >= 1 ? 1 : 2)}\u00a0доллара`

/**
 * Цена выходного токена на своих GPU для тех же запросов, что в примере закона Литтла (промпт 1000, ответ 300):
 * модель из симулятора на H100 (TP такой, чтобы влезали 32 запроса), только время decode, без prefill и простоя.
 */
function useTokenCost() {
  const [settings] = useSettings()
  return useMemo(() => {
    const g = getGpu('h100-sxm')
    const tpFor = (m: ModelLike) => [1, 2, 4, 8].find((tp) => maxConcurrentSeqs(m, g, { contextLen: 1300, gpus: tp, memUtil: MEM_UTIL }) >= 32) ?? 0
    let m: ModelLike = findModel(settings.modelId) ?? getModel('qwen3-8b')
    let tp = tpFor(m)
    if (!tp) {
      m = getModel('qwen3-8b')
      tp = 1
    }
    const row = (batch: number) => {
      const itl = decodeStepMs(m, g, { batch, avgContext: 1150, gpus: tp })
      const tps = (batch * 1000) / itl
      return { tps, user: 1000 / itl, cost: ((GPU_HOUR_USD * tp) / (tps * 3600)) * 1e6 }
    }
    const bMax = maxConcurrentSeqs(m, g, { contextLen: 1300, gpus: tp, memUtil: MEM_UTIL })
    const table = [...[1, 8, 32, 128].filter((b) => b < bMax), bMax].map((b) => ({ batch: b, ...row(b) }))
    return { model: m.name, tp, hw: tp > 1 ? `${tp} × H100` : 'H100', r1: row(1), r32: row(32), rMax: row(bMax), bMax, table }
  }, [settings.modelId])
}

