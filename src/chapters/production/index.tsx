      <Deeper title="формулы автоскейлеров и Planner">
        <h4>Kubernetes HPA</h4>
        <p>
          <Formula tex="\text{desired} = \left\lceil \text{current}\cdot \frac{m_{\text{cur}}}{m_{\text{target}}} \right\rceil" />, пересчёт
          раз в 15 секунд; при отклонении метрики от цели меньше чем на 10&nbsp;% ничего не меняется. Увеличение по умолчанию без задержки (до
          +100&nbsp;% или +4 подов за 15 секунд), уменьшение только после 300 секунд стабильно низкой метрики. Scale to zero (
          <code>minReplicas: 0</code>) возможен только по внешним или объектным метрикам: по CPU и памяти нельзя, их меряют на живых подах.
        </p>
        <h4>Почему целятся в 70&nbsp;%</h4>
        <p>
          В модели очереди M/M/1 время в системе <Formula tex="W = 1/(\mu - \lambda)" />. При обслуживании 10 запросов в секунду и приходе 5
          запрос проводит в системе 200 мс, при 9 уже секунду, при 9,9 десять секунд. LLM-сервер с continuous batching не M/M/1, но форма
          «хоккейной клюшки» у любой очереди та же.
        </p>
        <h4>Dynamo Planner</h4>
        <p>
          Классические формулы (Planner v1.0) считают реплики из прогноза на следующий интервал: нагрузка prefill = запросов × средний ISL /
          интервал, делённая на пропускную способность GPU из профиля; нагрузка decode = запросов × средний OSL / интервал, делённая на
          пропускную способность при заданном ITL. Условный пример (формулы из документации, числа иллюстративные): 1&nbsp;800 запросов за 180
          секунд, ISL 3&nbsp;000, OSL 300, prefill-GPU даёт 15&nbsp;000 токенов в секунду, decode-движок на двух GPU по 600 токенов в секунду на
          GPU: выходит 2 prefill- и 3 decode-реплики, ровно 8 GPU бюджета по умолчанию.
        </p>
        <p>
          Текущий Planner добавил реактивный контур по ForwardPassMetrics: онлайн-регрессии времени шага от числа токенов, решения ±1 реплика
          раз в 5 секунд, а медленный прогнозный контур задаёт пол. Цели по умолчанию в режиме SLA: TTFT 500 мс и ITL 50 мс; в режиме{' '}
          <code>advisory</code> Planner только советует.
        </p>
      </Deeper>

