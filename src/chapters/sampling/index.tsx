const OFF = { topK: 0, topP: 1, minP: 0 }

/** Пример ответа API с logprobs, посчитанный по условному распределению главы (T = 1, без отсечений). */
function logprobsJson(): string {
  const d = computeDist(HEAD, TAIL, { temperature: 1, ...OFF })
  const top = d.rows
    .filter((r) => !r.tail)
    .sort((a, b) => b.before - a.before)
    .slice(0, 3)
  const lp = (p: number) => Math.round(Math.log(p) * 1000) / 1000
  const obj = {
    logprobs: {
      content: [
        {
          token: top[0].text,
          logprob: lp(top[0].before),
          top_logprobs: top.map((r) => ({ token: r.text, logprob: lp(r.before) })),
        },
      ],
    },
  }
  return JSON.stringify(obj, null, 2)
}

