import { useMemo } from 'react'
import { stepWeightBytes, decodeStepBreakdown } from '@/engine/perf'
import { Callout, Chapter, ChapterLink, Deeper, Formula, SimulatorLink, Takeaways, Term, fmt } from '@/ui'
import { BatchSweep } from './BatchSweep'
import { Methods } from './Methods'
import { PassCost } from './PassCost'
import { useRunningExample } from './runningExample'
import { SpecAnimation } from './SpecAnimation'
import { SpeedupCalc } from './SpeedupCalc'

function useDecodeFacts() {
  const { model, gpu } = useRunningExample()
  return useMemo(() => {
    const step = decodeStepBreakdown(model, gpu, { batch: 1, avgContext: 1000 })
    return {
      model: model.name,
      gpu: gpu.name,
      weights: fmt.bytes(stepWeightBytes(model, 'bf16', 1)),
      intensity: fmt.num(step.intensity, 1),
      stepMs: fmt.ms(step.ms),
    }
  }, [model, gpu])
}

