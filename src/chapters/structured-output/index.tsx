/**
 * Перед переходом к стадии decode включает в симуляторе ответ по JSON-схеме: иначе на decode нет маски.
 * Свой текст читателя не трогаем (включаем только JSON), пресет меняем на «JSON по схеме».
 */
function enableJsonInSimulator() {
  const st = getSettings()
  if (st.json) return
  if (st.scenarioId === 'custom' && st.userText.trim()) patchSettings({ json: true })
  else patchSettings(scenarioPatch('json'))
}

