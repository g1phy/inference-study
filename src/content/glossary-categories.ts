/**
 * Подписи категорий глоссария (в данных категории записаны строчными). Отдельный модуль без JSON:
 * <Term> берёт подписи отсюда и не тянет весь глоссарий в критический чанк.
 */
export const CATEGORY_LABEL: Readonly<Record<string, string>> = {
  основы: 'Основы',
  модель: 'Модель',
  железо: 'Железо',
  движки: 'Движки',
  кэш: 'Кэш',
  планирование: 'Планирование',
  дезагрегация: 'Дезагрегация',
  dynamo: 'Dynamo',
  'вход-выход': 'Вход и выход',
  оптимизации: 'Оптимизации',
  метрики: 'Метрики',
  прод: 'Прод',
}

/** Подпись категории: «вход-выход» → «Вход и выход»; неизвестная категория с заглавной буквы. */
export function categoryLabel(c: string): string {
  return CATEGORY_LABEL[c] ?? (c ? c[0].toUpperCase() + c.slice(1) : c)
}
